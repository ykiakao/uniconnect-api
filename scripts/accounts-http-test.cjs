const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { startLocalHarness } = require('./lib/stage9-local.cjs');

async function main() {
  let h, checks = 0, requests = 0, phase = 'startup', result = 'FAIL';
  const check = (condition) => { assert.ok(condition); checks++; };
  try {
    h = await startLocalHarness();
    const api = async (method, path, token, body, status = 200, slug, key) => {
      requests++;
      const headers = {};
      if (token) headers.authorization = `Bearer ${token}`;
      if (slug) headers['x-tenant-slug'] = slug;
      if (key) headers['idempotency-key'] = key;
      if (body !== undefined) headers['content-type'] = 'application/json';
      const response = await fetch(`${h.apiOrigin}/api/v1${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
      const data = response.status === 204 ? null : await response.json();
      if (response.status !== status) throw Object.assign(new Error('Unexpected HTTP status'), { safeStatus: response.status, safeCode: data?.error?.code });
      check(response.status === status);
      check(response.headers.get('cache-control') === 'no-store, private');
      check(Boolean(response.headers.get('x-request-id')));
      if (status >= 400) check(data.error.requestId === response.headers.get('x-request-id'));
      return { data, requestId: response.headers.get('x-request-id') };
    };
    const actor = await h.createAuth('platform@p03.invalid');
    const env = require('../dist/config/env.js').env;
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [actor.id];
    const login = (await api('POST', '/auth/platform/login', undefined, { email: actor.email, password: h.password })).data;
    let token = login.accessToken;
    phase = 'platform rotation and allowlist';
    const rotated = (await api('POST', '/auth/platform/refresh', undefined, { refreshToken: login.refreshToken })).data;
    check(rotated.authorization.scope === 'platform' && !rotated.user);
    token = rotated.accessToken;
    await api('POST', '/auth/platform/refresh', undefined, { refreshToken: login.refreshToken }, 401);
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [];
    await api('POST', '/auth/platform/refresh', undefined, { refreshToken: rotated.refreshToken }, 403);
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [actor.id];
    const created = (await api('POST', '/platform/institutions', token, { name: 'Synthetic P03', slug: 'p03-synthetic' }, 201, undefined, randomUUID())).data;
    const base = `/platform/institutions/${created.id}`;
    phase = 'durable provisioning and no automatic grant';
    await api('GET', `${base}/admin-provisioning`, undefined, undefined, 401);
    const email = 'invited-admin@p03.invalid', input = { name: 'Synthetic Administrator', email }, key = randomUUID();
    const prepared = (await api('POST', `${base}/admin-provisioning`, token, input, 202, undefined, key)).data;
    check(prepared.state === 'awaiting_confirmation');
    check(!JSON.stringify(prepared).includes(email));
    check((await h.db.query('select count(*)::int n from app_users where tenant_id=$1', [created.id])).rows[0].n === 0);
    const repeated = (await api('POST', `${base}/admin-provisioning`, token, input, 202, undefined, key)).data;
    check(repeated.id === prepared.id);
    await api('POST', `${base}/admin-provisioning`, token, { ...input, name: 'Different' }, 409, undefined, key);
    const competing = await Promise.all([1, 2].map(() => api('POST', `${base}/admin-provisioning`, token, input, 202, undefined, randomUUID())));
    check(competing.every(x => x.data.id === prepared.id));
    check((await h.db.query('select count(*)::int n from auth.users where email=$1', [email])).rows[0].n === 1);
    check((await h.db.query("select count(*)::int n from platform_audit_events where tenant_id=$1 and action='account_invite_requested'", [created.id])).rows[0].n === 1);
    check((await api('GET', `${base}/admin-provisioning?page=1&limit=1`, token)).data.meta.total === 1);
    check((await api('GET', `${base}/admin-provisioning/${prepared.id}`, token)).data.id === prepared.id);
    await api('POST', `${base}/bootstrap-admin`, token, input, 409, undefined, randomUUID());
    phase = 'invite proof activation';
    const proof = h.createProof(email, 'invite');
    await api('POST', '/auth/password/reset', undefined, { tokenHash: proof, newPassword: h.password }, 401);
    await api('POST', '/auth/accounts/activate', undefined, { tokenHash: proof, newPassword: h.password }, 204);
    await api('POST', '/auth/accounts/activate', undefined, { tokenHash: proof, newPassword: h.password }, 401);
    check((await api('POST', `${base}/admin-provisioning/${prepared.id}/resume`, token, {}, 202)).data.state === 'ready');
    const bootstrapKey = randomUUID();
    const bootstrap = (await api('POST', `${base}/bootstrap-admin`, token, input, 201, undefined, bootstrapKey)).data;
    check((await api('GET', `${base}/responsible`, token)).data.responsibleUserId === bootstrap.administrator.id);
    const institutionalLogin = (await api('POST', '/auth/admin/login', undefined, { email, password: h.password }, 200, created.slug)).data;
    const institutional = institutionalLogin.accessToken;
    await api('GET', `${base}/admin-provisioning`, institutional, undefined, 403);
    await api('POST', `${base}/responsible/replace`, institutional, { email, name: input.name, expectedVersion: 1 }, 403, undefined, randomUUID());
    phase = 'institution rotation and current permissions';
    await api('POST', '/auth/refresh', undefined, { refreshToken: institutionalLogin.refreshToken }, 400);
    const instRotation = (await api('POST', '/auth/admin/refresh', undefined, { refreshToken: institutionalLogin.refreshToken }, 200, created.slug)).data;
    check(instRotation.user.role === 'admin' && instRotation.user.id === bootstrap.administrator.id);
    await h.db.query('update app_users set active=false where id=$1', [bootstrap.administrator.id]).then(() => { throw new Error('Responsible guard failed'); }, error => check(error.code === '23514'));
    phase = 'suspension blocks issued sessions and refresh';
    await api('POST', `${base}/suspend`, token, { expectedVersion: 1 }, 200, undefined, randomUUID());
    await api('POST', '/auth/refresh', undefined, { refreshToken: instRotation.refreshToken }, 403, created.slug);
    await api('GET', '/auth/me', instRotation.accessToken, undefined, 403, created.slug);
    await api('GET', `${base}/responsible`, token);
    await api('POST', `${base}/reactivate`, token, { expectedVersion: 2 }, 200, undefined, randomUUID());
    const afterSuspension = (await api('POST', '/auth/admin/refresh', undefined, { refreshToken: instRotation.refreshToken }, 200, created.slug)).data;
    check(afterSuspension.user.id === bootstrap.administrator.id);
    phase = 'responsible replacement and preserved history';
    const next = await h.createAuth('next-admin@p03.invalid');
    const replace = { email: next.email, name: 'Next Synthetic Admin', expectedVersion: 1 }, replacementKey = randomUUID();
    const replacement = (await api('POST', `${base}/responsible/replace`, token, replace, 200, undefined, replacementKey)).data;
    check(replacement.version === 2 && replacement.responsibleUserId !== bootstrap.administrator.id);
    check((await api('POST', `${base}/responsible/replace`, token, replace, 200, undefined, replacementKey)).data.version === 2);
    await api('POST', `${base}/responsible/replace`, token, replace, 409, undefined, randomUUID());
    await api('POST', '/auth/admin/refresh', undefined, { refreshToken: afterSuspension.refreshToken }, 403, created.slug);
    await api('GET', '/auth/me', afterSuspension.accessToken, undefined, 403, created.slug);
    await api('POST', `${base}/bootstrap-admin`, token, input, 201, undefined, bootstrapKey);
    check((await api('GET', `${base}/responsible`, token)).data.responsibleUserId === replacement.responsibleUserId);
    const history = (await api('GET', `${base}/responsible/history`, token)).data;
    check(history.data.length === 2 && history.data[1].previousUserId === bootstrap.administrator.id && history.data[1].targetUserId === replacement.responsibleUserId);
    check(!JSON.stringify(history).includes('@p03.invalid'));
    const teacher = await h.createAuth('teacher@p03.invalid');
    const other = (await api('POST', '/platform/institutions', token, { name: 'Other Synthetic', slug: 'p03-other' }, 201, undefined, randomUUID())).data;
    await h.db.query("insert into app_users(tenant_id,auth_user_id,name,email,role,active) values($1,$2,'Teacher',$3,'teacher',true)", [other.id, teacher.id, teacher.email]);
    const teacherLogin = (await api('POST', '/auth/login', undefined, { email: teacher.email, password: h.password }, 200, other.slug)).data;
    await api('POST', '/auth/admin/refresh', undefined, { refreshToken: teacherLogin.refreshToken }, 403, other.slug);
    await api('POST', '/auth/refresh', undefined, { refreshToken: h.refreshTokenFor(teacher.id) }, 403, created.slug);
    await h.db.query("update app_users set role='student' where auth_user_id=$1", [teacher.id]);
    check((await api('POST', '/auth/refresh', undefined, { refreshToken: h.refreshTokenFor(teacher.id) }, 200, other.slug)).data.user.role === 'aluno');
    await api('GET', `/platform/institutions/${other.id}/admin-provisioning/${prepared.id}`, token, undefined, 404);
    phase = 'recovery anti enumeration and one-time provider proofs';
    const recoveryKnown = (await api('POST', '/auth/password/recovery', undefined, { email: next.email }, 202)).data;
    const recoveryUnknown = (await api('POST', '/auth/password/recovery', undefined, { email: 'missing@p03.invalid' }, 202)).data;
    check(JSON.stringify(recoveryKnown) === JSON.stringify(recoveryUnknown));
    const expired = h.createProof(next.email, 'recovery', { expired: true });
    await api('POST', '/auth/password/reset', undefined, { tokenHash: expired, newPassword: h.password }, 401);
    const recovery = h.createProof(next.email, 'recovery');
    const beforeResetRefresh = h.refreshTokenFor(next.id);
    await api('POST', '/auth/accounts/activate', undefined, { tokenHash: recovery, newPassword: h.password }, 401);
    await api('POST', '/auth/password/reset', undefined, { tokenHash: recovery, newPassword: h.password }, 204);
    await api('POST', '/auth/refresh', undefined, { refreshToken: beforeResetRefresh }, 401, created.slug);
    await api('POST', '/auth/password/reset', undefined, { tokenHash: recovery, newPassword: h.password }, 401);
    const revoked = h.refreshTokenFor(next.id); h.revokeSessions(next.id);
    await api('POST', '/auth/refresh', undefined, { refreshToken: revoked }, 401, created.slug);
    check(h.stats.forbiddenNetwork === 0);
    result = 'PASS';
  } catch (error) {
    throw new Error(`P0.3 local HTTP failed at ${phase}${error.safeStatus ? ` (HTTP ${error.safeStatus}, ${error.safeCode || 'no code'})` : ''}; private details withheld.`);
  } finally {
    if (h) {
      try { await h.close(); } catch { result = 'FAIL'; }
      const evidence = { ...h.evidence, stage: 'P0.3', result, checks, httpRequests: requests, phase, transport: h.stats, auth: 'Synthetic local provider; no GoTrue internals, mail or remote Supabase validated.' };
      writeFileSync(join(__dirname, '../docs/evidence', process.argv.includes('--p0-4-regression') ? 'p0-4-p03-http.json' : 'p0-3-http.json'), JSON.stringify(evidence, null, 2) + '\n');
      console.log(JSON.stringify({ result, checks, httpRequests: requests, phase, cleanup: evidence.cleanup, forbiddenNetwork: h.stats.forbiddenNetwork }));
      if (result !== 'PASS') process.exitCode = 1;
    }
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });

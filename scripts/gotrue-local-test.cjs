const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { startGoTrueHarness } = require('./lib/gotrue-local.cjs');

async function main() {
  const evidence = { stage: 'P0.4 real GoTrue', startedAt: new Date().toISOString(), result: 'FAIL', phase: 'startup', checks: 0, httpRequests: 0, sdkVersions: { supabase: require('@supabase/supabase-js/package.json').version, auth: require('@supabase/auth-js/package.json').version }, observations: {} };
  let h;
  const check = condition => { assert.ok(condition); evidence.checks++; };
  const noError = result => { if (result.error) throw Object.assign(new Error('Local SDK operation rejected.'), { safeCode: result.error.code, safeStatus: result.error.status }); check(true); return result.data; };
  const rejected = result => { check(Boolean(result.error)); return { code: result.error.code, status: result.error.status }; };
  try {
    h = await startGoTrueHarness(evidence);
    const api = async (method, path, body, status = 200, { token, slug, key } = {}) => {
      evidence.httpRequests++;
      const headers = {};
      if (token) headers.authorization = `Bearer ${token}`;
      if (slug) headers['x-tenant-slug'] = slug;
      if (key) headers['idempotency-key'] = key;
      if (body !== undefined) headers['content-type'] = 'application/json';
      const response = await fetch(`${h.apiOrigin}/api/v1${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
      const data = response.status === 204 ? null : await response.json();
      if (response.status !== status) throw Object.assign(new Error('Unexpected HTTP response.'), { safeStatus: response.status, safeCode: data?.error?.code });
      check(response.status === status); check(response.headers.get('cache-control') === 'no-store, private'); check(Boolean(response.headers.get('x-request-id')));
      if (status >= 400) check(data.error.requestId === response.headers.get('x-request-id'));
      return data;
    };
    evidence.phase = 'real SDK refresh rotation, reuse semantics and revocation';
    const actor = await h.createAuth('actor@p04.invalid');
    const SDKlogin = () => h.client().auth.signInWithPassword({ email: actor.email, password: h.password });
    const first = noError(await SDKlogin()).session;
    const second = noError(await h.client().auth.refreshSession({ refresh_token: first.refresh_token })).session;
    check(first.refresh_token !== second.refresh_token);
    check(noError(await h.client().auth.getUser(second.access_token)).user.id === actor.id);
    const parentReuse = await h.client().auth.refreshSession({ refresh_token: first.refresh_token });
    evidence.observations.parentRefreshReuse = parentReuse.error ? { accepted: false, ...rejected(parentReuse) } : { accepted: true };
    if (!parentReuse.error) check(parentReuse.data.session.user.id === actor.id);
    const current = parentReuse.error ? second : parentReuse.data.session;
    const third = noError(await h.client().auth.refreshSession({ refresh_token: current.refresh_token })).session;
    await new Promise(resolve => setTimeout(resolve, 1100));
    const ancestorReuse = await h.client().auth.refreshSession({ refresh_token: first.refresh_token });
    evidence.observations.ancestorRefreshReuse = ancestorReuse.error ? { accepted: false, ...rejected(ancestorReuse) } : { accepted: true };
    if (!ancestorReuse.error) check(ancestorReuse.data.session.user.id === actor.id);
    evidence.observations.invalidRefresh = rejected(await h.client().auth.refreshSession({ refresh_token: 'synthetic-invalid-refresh-token' }));
    evidence.phase = 'compiled API malformed refresh returns INVALID_SESSION';
    const malformedRefresh = await api('POST', '/auth/platform/refresh', { refreshToken: 'synthetic-invalid-refresh-token' }, 401);
    check(malformedRefresh.error.code === 'INVALID_SESSION');
    evidence.observations.malformedRefreshHttp = { status: 401, code: malformedRefresh.error.code };
    const beforeLogout = noError(await SDKlogin()).session;
    noError(await h.client().auth.admin.signOut(beforeLogout.access_token, 'global'));
    evidence.observations.globalLogoutRefresh = rejected(await h.client().auth.refreshSession({ refresh_token: beforeLogout.refresh_token }));
    const jwtAfterLogout = await h.client().auth.getUser(beforeLogout.access_token);
    evidence.observations.accessJwtAfterGlobalLogout = jwtAfterLogout.error ? { accepted: false, ...rejected(jwtAfterLogout) } : { accepted: true };
    const expiring = noError(await SDKlogin()).session;
    const sessionId = JSON.parse(Buffer.from(expiring.access_token.split('.')[1], 'base64url').toString()).session_id;
    await h.db.query("update auth.sessions set not_after=now()-interval '1 minute' where id=$1", [sessionId]);
    evidence.observations.expiredProviderSession = rejected(await h.client().auth.refreshSession({ refresh_token: expiring.refresh_token }));
    evidence.phase = 'compiled API platform rotation and allowlist';
    const env = require('../dist/config/env.js').env;
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [actor.id];
    const platformLogin = () => api('POST', '/auth/platform/login', { email: actor.email, password: h.password });
    const login = await platformLogin();
    const platform = await api('POST', '/auth/platform/refresh', { refreshToken: login.refreshToken });
    check(platform.authorization.scope === 'platform' && !platform.user);
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [];
    await api('POST', '/auth/platform/refresh', { refreshToken: platform.refreshToken }, 403);
    env.PLATFORM_ADMIN_AUTH_USER_IDS = [actor.id];
    const live = await platformLogin(), options = { token: live.accessToken };
    const institution = await api('POST', '/platform/institutions', { name: 'GoTrue Synthetic', slug: 'p04-gotrue' }, 201, { ...options, key: randomUUID() });
    const base = `/platform/institutions/${institution.id}`;
    evidence.phase = 'durable invitation, SMTP capture, activation and reconciliation';
    const invitedEmail = 'invited@p04.invalid', intent = { name: 'Synthetic Invited Admin', email: invitedEmail }, key = randomUUID();
    const provision = await api('POST', `${base}/admin-provisioning`, intent, 202, { ...options, key });
    check(provision.state === 'awaiting_confirmation');
    check(!JSON.stringify(provision).includes(invitedEmail));
    const replay = await api('POST', `${base}/admin-provisioning`, intent, 202, { ...options, key });
    check(replay.id === provision.id);
    check((await h.db.query('select count(*)::int n from auth.users where email=$1', [invitedEmail])).rows[0].n === 1);
    check((await h.db.query('select count(*)::int n from app_users where tenant_id=$1', [institution.id])).rows[0].n === 0);
    const invitation = await h.capture(invitedEmail, 'invite');
    await api('POST', '/auth/password/reset', { tokenHash: invitation, newPassword: h.password }, 401);
    await api('POST', '/auth/accounts/activate', { tokenHash: invitation, newPassword: h.password }, 204);
    await api('POST', '/auth/accounts/activate', { tokenHash: invitation, newPassword: h.password }, 401);
    check((await api('POST', `${base}/admin-provisioning/${provision.id}/resume`, {}, 202, options)).state === 'ready');
    const bootstrap = await api('POST', `${base}/bootstrap-admin`, intent, 201, { ...options, key: randomUUID() });
    check((await api('GET', `${base}/responsible`, undefined, 200, options)).responsibleUserId === bootstrap.administrator.id);
    evidence.phase = 'institution refresh, stale membership email and suspension';
    await h.db.query("update app_users set email='stale-membership@p04.invalid' where id=$1", [bootstrap.administrator.id]);
    const institutionalLogin = await api('POST', '/auth/admin/login', { email: invitedEmail, password: h.password }, 200, { slug: institution.slug });
    check(institutionalLogin.user.id === bootstrap.administrator.id);
    const institutional = await api('POST', '/auth/admin/refresh', { refreshToken: institutionalLogin.refreshToken }, 200, { slug: institution.slug });
    check(institutional.user.role === 'admin');
    await api('POST', `${base}/suspend`, { expectedVersion: 1 }, 200, { ...options, key: randomUUID() });
    await api('POST', '/auth/refresh', { refreshToken: institutional.refreshToken }, 403, { slug: institution.slug });
    await api('GET', '/auth/me', undefined, 403, { token: institutional.accessToken, slug: institution.slug });
    await api('POST', `${base}/reactivate`, { expectedVersion: 2 }, 200, { ...options, key: randomUUID() });
    evidence.phase = 'recovery email, official proof, password change and logout';
    const known = await api('POST', '/auth/password/recovery', { email: actor.email }, 202);
    const unknown = await api('POST', '/auth/password/recovery', { email: 'missing@p04.invalid' }, 202);
    check(JSON.stringify(known) === JSON.stringify(unknown));
    const proof = await h.capture(actor.email, 'recovery');
    await api('POST', '/auth/accounts/activate', { tokenHash: proof, newPassword: h.password }, 401);
    const prior = noError(await SDKlogin()).session;
    const changedPassword = `${h.password}changed`;
    await api('POST', '/auth/password/reset', { tokenHash: proof, newPassword: changedPassword }, 204);
    await api('POST', '/auth/password/reset', { tokenHash: proof, newPassword: changedPassword }, 401);
    await api('POST', '/auth/platform/refresh', { refreshToken: prior.refresh_token }, 401);
    rejected(await SDKlogin());
    const after = noError(await h.client().auth.signInWithPassword({ email: actor.email, password: changedPassword })).session;
    check(noError(await h.client().auth.getUser(after.access_token)).user.id === actor.id);
    await api('POST', '/auth/password/reset', { tokenHash: 'synthetic-invalid-proof', newPassword: changedPassword }, 401);
    await api('POST', '/auth/password/reset', { tokenHash: after.access_token, newPassword: changedPassword }, 401);
    const expiryUser = await h.createAuth('expiry@p04.invalid');
    await api('POST', '/auth/password/recovery', { email: expiryUser.email }, 202);
    const expiredProof = await h.capture(expiryUser.email, 'recovery');
    await h.db.query("update auth.users set recovery_sent_at=now()-interval '2 hours' where id=$1", [expiryUser.id]);
    await api('POST', '/auth/password/reset', { tokenHash: expiredProof, newPassword: changedPassword }, 401);
    evidence.observations.expiredProofFixture = 'Real provider-issued proof; only its auth.users.recovery_sent_at backdated in disposable DB to exercise provider expiry.';
    check(h.stats.forbiddenNetwork === 0);
    evidence.phase = 'complete'; evidence.result = 'PASS';
  } catch (error) {
    evidence.failure = { phase: evidence.phase, startupPhase: evidence.startupPhase, status: error.safeStatus, code: error.safeCode || (/^[A-Z0-9_]{1,40}$/.test(error.code || '') ? error.code : undefined), category: /^[A-Za-z0-9 _.;:-]{1,160}$/.test(error.message) ? error.message : `Private diagnostic withheld (${error.name || 'Error'}).` };
    process.exitCode = 1;
  } finally {
    if (h) { try { await h.close(); } catch { evidence.result = 'FAIL'; process.exitCode = 1; } }
    evidence.finishedAt = new Date().toISOString();
    const file = `p0-4-gotrue-local-${evidence.startedAt.replace(/[:.]/g, '-')}.json`;
    writeFileSync(join(__dirname, '../docs/evidence', file), JSON.stringify(evidence, null, 2) + '\n');
    console.log(JSON.stringify({ result: evidence.result, phase: evidence.phase, checks: evidence.checks, httpRequests: evidence.httpRequests, failure: evidence.failure, cleanup: evidence.cleanup, evidence: file }));
  }
}
main().catch(() => { console.error('Local GoTrue runner failed; private diagnostic withheld.'); process.exitCode = 1; });
